#!/usr/bin/env bash
# Local macOS qualification receipt for one exact signed dev Runne.app.
#
# This is operational local evidence produced on the owner's dev signing keys.
# It is not third-party attestation and it is not release qualification.
set -euo pipefail
umask 077

usage() {
  cat <<'USAGE'
Usage: dev-macos-qualification-receipt.sh qualify --bundle PATH --artifact PATH --out DIR
                                                  [--validity-seconds N]

Runs the macOS qualification checks on one signed dev bundle and writes
DIR/receipt.json plus DIR/checks.log. It refuses a dirty tree, a bundle whose
staged release candidate is not the current commit, a reused output directory,
or a validity window longer than 14 days.

The receipt binds: source commit, release-candidate digest, artifact digest,
every measured tuple-V3 input, the check commands and their exit statuses, and
the qualification window. It is generated only from the finalize workflow
(RUNNE_FINALIZE_QUALIFICATION=1).

Exit codes: 0 receipt written, 1 check or precondition failed, 2 usage error.
USAGE
}

fail() { echo "error: $*" >&2; exit 1; }

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$repo_root"

[[ $# -ge 1 && "$1" == "qualify" ]] || { usage >&2; exit 2; }
shift
bundle=""
artifact=""
out=""
validity=604800
while [[ $# -gt 0 ]]; do
  case "$1" in
    --bundle) [[ $# -ge 2 ]] || fail "--bundle requires a value"; bundle="$2"; shift 2 ;;
    --artifact) [[ $# -ge 2 ]] || fail "--artifact requires a value"; artifact="$2"; shift 2 ;;
    --out) [[ $# -ge 2 ]] || fail "--out requires a value"; out="$2"; shift 2 ;;
    --validity-seconds) [[ $# -ge 2 ]] || fail "--validity-seconds requires a value"; validity="$2"; shift 2 ;;
    *) usage >&2; exit 2 ;;
  esac
done
[[ -n "$bundle" && -n "$artifact" && -n "$out" ]] || { usage >&2; exit 2; }
[[ "${RUNNE_FINALIZE_QUALIFICATION:-}" == "1" ]] \
  || fail "qualification receipts are generated by dev-macos-signed-workflow.sh qualify"
[[ "$(uname -s):$(uname -m)" == "Darwin:arm64" ]] || fail "requires macOS arm64"
[[ "$validity" =~ ^[0-9]+$ ]] && (( validity > 0 && validity <= 1209600 )) \
  || fail "--validity-seconds must be 1..1209600"

require_clean_source() {
  git diff --quiet HEAD -- || fail "source tree has tracked changes; commit before qualification"
  # The local tool scratch directory is not a build input.
  [[ -z "$(git status --porcelain --untracked-files=all -- . ':(exclude).tmp-tools')" ]] \
    || fail "source tree has untracked files; commit or remove them before qualification"
}

[[ -d "$bundle" ]] || fail "bundle not found: $bundle"
[[ -f "$artifact" ]] || fail "artifact not found: $artifact"
require_clean_source
source_commit="$(git rev-parse --verify HEAD^{commit})"
commit_digest="$(printf '%s' "$source_commit" | shasum -a 256 | awk '{print $1}')"
binding="$bundle/Contents/Resources/native-enrollment/release-candidate-binding.json"
[[ -f "$binding" ]] || fail "bundle has no staged release-candidate binding"
binding_candidate="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["releaseCandidateSha256"])' "$binding")"
[[ "$binding_candidate" == "$commit_digest" ]] \
  || fail "bundle release candidate $binding_candidate is not this commit $source_commit; rebuild the bundle"

mkdir -p "$out"
receipt="$out/receipt.json"
log="$out/checks.log"
[[ ! -e "$receipt" && ! -L "$receipt" && ! -e "$log" && ! -L "$log" ]] \
  || fail "receipt or log already exists in $out; qualification refuses to reuse evidence"

abs_bundle="$(cd "$bundle" && pwd)"
abs_artifact="$(cd "$(dirname "$artifact")" && pwd)/$(basename "$artifact")"
component_paths=(
  "Contents/MacOS/runne-desktop"
  "Contents/MacOS/runne"
  "Contents/MacOS/runned"
  "Contents/Library/Helpers/RunneCredentialService.app/Contents/MacOS/runne-credential-service"
  "Contents/Library/LaunchAgents/com.runne.credential-service.plist"
  "Contents/Resources/native-enrollment/credential-service.entitlements.plist"
  "Contents/Library/Helpers/RunneCredentialService.app/Contents/embedded.provisionprofile"
  "Contents/Resources/native-enrollment/xpc-protocol-v1.json"
  "Contents/Resources/contracts/gocode-ui-client-3/bundle.json"
)
for relative in "${component_paths[@]}"; do
  [[ -f "$bundle/$relative" ]] || fail "bundle lacks required component: $relative"
done

printf '$ %s\n' "cargo test -p runne-platform-desktop --lib updater_metadata" >"$log"
test_status=0
cargo test -p runne-platform-desktop --lib updater_metadata >>"$log" 2>&1 || test_status=$?
printf '\n$ %s\n' "codesign --verify --strict --verbose=2 $abs_bundle" >>"$log"
codesign_status=0
codesign --verify --strict --verbose=2 "$abs_bundle" >>"$log" 2>&1 || codesign_status=$?
printf '\n$ %s\n' "sha256 of the nine measured tuple inputs" >>"$log"
component_status=0
for relative in "${component_paths[@]}"; do
  digest="$(shasum -a 256 "$bundle/$relative" | awk '{print $1}')"
  [[ "$digest" =~ ^[0-9a-f]{64}$ ]] || { component_status=1; echo "unmeasurable: $relative" >>"$log"; }
  printf '%s  %s\n' "$digest" "$relative" >>"$log"
done
[[ $test_status == 0 && $codesign_status == 0 && $component_status == 0 ]] || {
  echo "qualification failed (tests=$test_status codesign=$codesign_status components=$component_status); log: $log" >&2
  exit 1
}
require_clean_source
[[ "$(git rev-parse --verify HEAD^{commit})" == "$source_commit" ]] \
  || fail "source commit changed while qualification was running"

BUNDLE="$abs_bundle" ARTIFACT="$abs_artifact" RECEIPT="$receipt" LOG="$log" \
SOURCE_COMMIT="$source_commit" COMMIT_DIGEST="$commit_digest" VALIDITY="$validity" \
python3 <<'PYRECEIPT'
import hashlib, json, os, pathlib, time

def digest(path):
    value = hashlib.sha256()
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()

bundle = pathlib.Path(os.environ["BUNDLE"])
components = {
    "desktopSha256": "Contents/MacOS/runne-desktop",
    "writerSha256": "Contents/MacOS/runne",
    "daemonSha256": "Contents/MacOS/runned",
    "credentialServiceSha256": "Contents/Library/Helpers/RunneCredentialService.app/Contents/MacOS/runne-credential-service",
    "launchAgentPlistSha256": "Contents/Library/LaunchAgents/com.runne.credential-service.plist",
    "entitlementsSha256": "Contents/Resources/native-enrollment/credential-service.entitlements.plist",
    "provisioningSha256": "Contents/Library/Helpers/RunneCredentialService.app/Contents/embedded.provisionprofile",
    "xpcProtocolSha256": "Contents/Resources/native-enrollment/xpc-protocol-v1.json",
    "contractSha256": "Contents/Resources/contracts/gocode-ui-client-3/bundle.json",
}
qualified_at = int(time.time())
receipt = {
    "schemaVersion": 1,
    "platform": "macos",
    "architecture": "arm64",
    "sourceCommit": os.environ["SOURCE_COMMIT"],
    "releaseCandidateSha256": os.environ["COMMIT_DIGEST"],
    "artifactSha256": digest(os.environ["ARTIFACT"]),
    **{key: digest(bundle / relative) for key, relative in components.items()},
    "checks": ["updater-metadata-tests", "codesign-bundle-strict", "bundle-component-digests"],
    "checkCommands": [
        "cargo test -p runne-platform-desktop --lib updater_metadata",
        "codesign --verify --strict --verbose=2 Runne.app",
        "bundle component sha256 match against the measured tuple inputs",
    ],
    "checkExitStatuses": [0, 0, 0],
    "checkLogSha256": digest(os.environ["LOG"]),
    "qualifiedAtUnixSeconds": qualified_at,
    "expiresAtUnixSeconds": qualified_at + int(os.environ["VALIDITY"]),
}
with open(os.environ["RECEIPT"], "x", encoding="utf-8") as output:
    json.dump(receipt, output, separators=(",", ":"))
    output.write("\n")
PYRECEIPT

echo "Qualification receipt: $receipt"
echo "Check log: $log"
echo "Evidence scope: local operational evidence on dev keys, not third-party attestation and not release qualification."
