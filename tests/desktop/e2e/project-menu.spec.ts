import { expect, test } from '@playwright/test'
import { installDesktopAdapter, project } from './replay-resume.support'

test('project menu dismisses and renames the canonical project in the sidebar', async ({ page }) => {
  await installDesktopAdapter(page, true)
  await page.goto(`/projects/${project.projectId}`)
  const expandSidebar = page.getByRole('button', { name: 'Expand sidebar', exact: true })
  if (await expandSidebar.isVisible()) await expandSidebar.click()
  const menu = page.getByRole('button', { name: 'Manage project', exact: true })
  const rename = page.getByRole('menuitem', { name: 'Rename project', exact: true })
  await expect(page.getByRole('button', { name: 'Collapse project tree for gocode-ui', exact: true })).toBeVisible()
  await expect(rename).toBeHidden()
  await menu.click()
  await expect(page.getByRole('menu')).toBeVisible()
  await expect(rename).toBeVisible()
  await expect(rename).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(rename).toBeHidden()
  await expect(menu).toBeFocused()
  await menu.click()
  await page.getByRole('heading', { name: 'Projects', exact: true }).click()
  await expect(rename).toBeHidden()
  await menu.click()
  await rename.click()
  const input = page.getByRole('textbox', { name: 'Project name', exact: true })
  await expect(input).toHaveValue(project.displayName)
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeDisabled()
  await input.fill('Runne editor')
  await input.press('Enter')
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByRole('button', { name: 'Collapse project tree for Runne editor', exact: true })).toBeVisible()
  await menu.click()
  await page.screenshot({ path: 'test-results/project-actions-menu.png' })
})
