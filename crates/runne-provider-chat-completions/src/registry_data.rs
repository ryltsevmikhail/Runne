//! Model and endpoint metadata is pinned to the local `@earendil-works/pi-ai`
//! 0.85.1 snapshot (generated 2026-09-05, source SHA
//! `71dca871bc80b6bc97be37f0ca3189399d651fff`). It is compatibility metadata,
//! not live qualification or a subscription price source. The conservative
//! registry bound is 65,536 input bytes and 16,384 output tokens for all 23
//! entries; it fits the independently checked smallest pinned contexts
//! (128,000/131,072 tokens) with bounded protocol overhead.
use super::GenericChatProfile;
use crate::{ChatCompletionsProfile, ChatCompletionsThinkingMode};
#[path = "registry_accounting.rs"]
mod accounting_data;
#[path = "registry_digests.rs"]
mod registry_digests;
const REVISION: &str = "pi-ai-0.85.1-2026-09-05";
const MAX_INPUT_BYTES: usize = 65_536;
const MAX_OUTPUT_TOKENS: u32 = 16_384;
#[allow(clippy::too_many_arguments)]
const fn profile(
    provider_id: &'static str,
    profile_id: &'static str,
    model_id: &'static str,
    origin: &'static str,
    path: &'static str,
    digests: ([u8; 32], [u8; 32]),
    thinking: ChatCompletionsThinkingMode,
    include_stream_usage: bool,
) -> GenericChatProfile {
    GenericChatProfile {
        provider_id,
        profile_id,
        profile: ChatCompletionsProfile::new_with_accounting(
            provider_id,
            profile_id,
            model_id,
            REVISION,
            origin,
            path,
            digests.0,
            digests.1,
            64,
            65_536,
            MAX_INPUT_BYTES,
            MAX_OUTPUT_TOKENS,
            524_288,
            65_536,
            accounting_data::for_provider(provider_id),
            thinking,
        )
        .with_stream_usage(include_stream_usage),
    }
}

