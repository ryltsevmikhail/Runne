CREATE TABLE managed_policy_admin_commands (
    command_id BLOB PRIMARY KEY CHECK(length(command_id) = 16),
    idempotency_key TEXT NOT NULL CHECK(length(idempotency_key) BETWEEN 1 AND 256),
    stable_subject_digest BLOB NOT NULL CHECK(length(stable_subject_digest) = 32),
    authority_id BLOB NOT NULL CHECK(length(authority_id) = 16),
    lineage_id BLOB NOT NULL CHECK(length(lineage_id) = 16),
    project_id BLOB NOT NULL CHECK(length(project_id) = 16),
    project_epoch INTEGER NOT NULL CHECK(project_epoch > 0),
    expected_revision INTEGER NOT NULL CHECK(expected_revision > 0),
    old_rules_digest BLOB NOT NULL CHECK(length(old_rules_digest) = 32),
    new_rules_digest BLOB NOT NULL CHECK(length(new_rules_digest) = 32),
    managed_version INTEGER NOT NULL CHECK(managed_version = 1),
    source_policy_version INTEGER NOT NULL CHECK(source_policy_version = 2),
    local_command_policy_version INTEGER NOT NULL CHECK(local_command_policy_version = 1),
    fs_read INTEGER NOT NULL CHECK(fs_read BETWEEN 0 AND 2),
    fs_create INTEGER NOT NULL CHECK(fs_create BETWEEN 0 AND 2),
    fs_write INTEGER NOT NULL CHECK(fs_write BETWEEN 0 AND 2),
    fs_delete INTEGER NOT NULL CHECK(fs_delete BETWEEN 0 AND 2),
    process_start INTEGER NOT NULL CHECK(process_start BETWEEN 0 AND 2),
    network_use INTEGER NOT NULL CHECK(network_use BETWEEN 0 AND 2),
    admin_generation INTEGER NOT NULL CHECK(admin_generation > 0),
    launch_binding_digest BLOB NOT NULL CHECK(length(launch_binding_digest) = 32),
    challenge_id BLOB NOT NULL UNIQUE CHECK(length(challenge_id) = 16),
    challenge_nonce BLOB NOT NULL UNIQUE CHECK(length(challenge_nonce) = 32),
    warning_version INTEGER NOT NULL CHECK(warning_version > 0),
    issued_at_unix_ms INTEGER NOT NULL CHECK(issued_at_unix_ms > 0),
    expires_at_unix_ms INTEGER NOT NULL CHECK(expires_at_unix_ms > issued_at_unix_ms),
    request_digest BLOB NOT NULL CHECK(length(request_digest) = 32),
    semantic_digest BLOB NOT NULL CHECK(length(semantic_digest) = 32),
    state INTEGER NOT NULL CHECK(state BETWEEN 1 AND 5),
    reserved_at_unix_ms INTEGER NOT NULL CHECK(reserved_at_unix_ms > 0),
    UNIQUE(stable_subject_digest, idempotency_key),
    FOREIGN KEY(stable_subject_digest) REFERENCES managed_policy_administrator(stable_subject_digest)
) STRICT
