/// Contract generation or byte-check failure.
#[derive(Debug, thiserror::Error)]
pub enum ContractGenerationError {
    /// A generated JSON value could not be serialized.
    #[error("serialize generated contract artifact")]
    Serialize(#[from] serde_json::Error),
    /// A generated artifact could not be read or written.
    #[error("access generated contract artifact: {0}")]
    Io(#[from] std::io::Error),
    /// Checked-in bytes differ from authoritative generated bytes.
    #[error("generated contract artifact differs: {0}")]
    ByteMismatch(PathBuf),
    /// The checked-in generated artifact set contains a missing or stale path.
    #[error("generated contract artifact path set differs")]
    ArtifactSetMismatch,
}

