const DRAFT_2020_12: &str = "https://json-schema.org/draft/2020-12/schema";
const UUID_V7_PATTERN: &str =
    "^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$";
